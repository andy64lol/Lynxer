//! JS Interop ABI — `wynxer_js_abi_v1`.
//!
//! Wynxer exposes a small, explicit ABI for calling JavaScript from `.wynx`
//! source. The ABI is a set of recognised builtins that the JS emitter
//! translates directly into JavaScript:
//!
//! | Wynxer call | Emitted JS |
//! | --- | --- |
//! | `js("raw code");` | raw JavaScript statement, verbatim |
//! | `jsExpr("expression")` | raw JavaScript expression |
//! | `jsImport("pkg", "a, b")` | `import { a, b } from "pkg"` (ESM) / `const { a, b } = require("pkg")` (Node CJS) |
//! | `jsRequire("pkg")` | `require("pkg")` expression |
//! | `jsGlobal("name")` | a global JS binding reference |
//!
//! This mirrors the role of Lynxer's native-module ABI: a stable, narrow
//! boundary between the language and the host runtime, with no magic
//! coercion of Wynxer values into JS values.

use crate::ast::Expr;

/// Version string of this ABI, emitted in generated file headers.
pub const ABI_VERSION: &str = "wynxer_js_abi_v1";

/// The JavaScript module target.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Target {
    /// Plain browser script (`<script src="app.js">`), no module syntax.
    Browser,
    /// Node.js. Honours `.wynxcfg` `type = module|commonjs`.
    NodeModule,
    /// Node.js CommonJS output (`.cjs`), uses `require`/`module.exports`.
    NodeCommonJs,
}

impl Target {
    pub fn label(&self) -> &'static str {
        match self {
            Target::Browser => "browser",
            Target::NodeModule => "node-esm",
            Target::NodeCommonJs => "node-cjs",
        }
    }
}

/// True if `callee` is the raw-statement ABI builtin.
pub fn is_raw_statement(callee: &str) -> bool {
    callee == "js"
}

/// True if `callee` is the raw-expression ABI builtin.
pub fn is_raw_expression(callee: &str) -> bool {
    callee == "jsExpr"
}

/// True if `callee` is the package-import ABI builtin.
pub fn is_import(callee: &str) -> bool {
    callee == "jsImport"
}

/// True if `callee` is the CommonJS-require ABI builtin.
pub fn is_require(callee: &str) -> bool {
    callee == "jsRequire"
}

/// True if `callee` is the global-binding ABI builtin.
pub fn is_global(callee: &str) -> bool {
    callee == "jsGlobal"
}

/// True when the callee is any recognised ABI builtin.
pub fn is_abi_call(callee: &str) -> bool {
    is_raw_statement(callee)
        || is_raw_expression(callee)
        || is_import(callee)
        || is_require(callee)
        || is_global(callee)
}

/// Extract a string-literal argument by index from an argument list.
/// Used by the emitter to read raw JS source and package names.
pub fn string_arg(args: &[Expr], index: usize) -> Option<String> {
    match args.get(index) {
        Some(Expr::Str(s)) => Some(s.clone()),
        _ => None,
    }
}

/// Emit an ABI header comment for a generated file.
pub fn header(target: Target) -> String {
    format!("// Generated by Wynxer — {} ({})\n", ABI_VERSION, target.label())
}

/// Emit an import statement for a JS/npm package.
///
/// - `names` is a comma-separated list of named imports (may be empty for a
///   side-effect import).
/// - Browser targets emit ES-module syntax (safe for bundlers); Node CommonJS
///   targets emit a `require` destructuring assignment.
pub fn emit_import(package: &str, names: &str, target: Target) -> String {
    let names = names.trim();
    match target {
        Target::NodeCommonJs => {
            if names.is_empty() {
                format!("require(\"{}\");", package)
            } else {
                format!(
                    "const {{ {} }} = require(\"{}\");",
                    names
                        .split(',')
                        .map(str::trim)
                        .filter(|s| !s.is_empty())
                        .collect::<Vec<_>>()
                        .join(", "),
                    package
                )
            }
        }
        _ => {
            if names.is_empty() {
                format!("import \"{}\";", package)
            } else {
                format!(
                    "import {{ {} }} from \"{}\";",
                    names
                        .split(',')
                        .map(str::trim)
                        .filter(|s| !s.is_empty())
                        .collect::<Vec<_>>()
                        .join(", "),
                    package
                )
            }
        }
    }
}

/// Split a `.wynxcfg` `deps` value into a list of package names.
pub fn parse_deps(value: &str) -> Vec<String> {
    value
        .split([',', ' ', '\n', '\t'])
        .map(str::trim)
        .filter(|s| !s.is_empty())
        .map(str::to_string)
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_recognised_builtins() {
        assert!(is_raw_statement("js"));
        assert!(is_raw_expression("jsExpr"));
        assert!(is_import("jsImport"));
        assert!(is_require("jsRequire"));
        assert!(is_global("jsGlobal"));
        assert!(!is_abi_call("println"));
    }

    #[test]
    fn test_emit_import_esm() {
        assert_eq!(
            emit_import("lodash", "map, filter", Target::NodeModule),
            "import { map, filter } from \"lodash\";"
        );
    }

    #[test]
    fn test_emit_import_cjs() {
        assert_eq!(
            emit_import("lodash", "map", Target::NodeCommonJs),
            "const { map } = require(\"lodash\");"
        );
    }

    #[test]
    fn test_parse_deps() {
        assert_eq!(parse_deps("lodash, chalk"), vec!["lodash", "chalk"]);
    }

    #[test]
    fn test_string_arg() {
        let args = vec![Expr::Str("hello".to_string())];
        assert_eq!(string_arg(&args, 0), Some("hello".to_string()));
        assert_eq!(string_arg(&args, 1), None);
    }
}
